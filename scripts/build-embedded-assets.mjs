#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const skillRoot = join(projectRoot, 'skills', 'business-posters');
const scriptRoot = join(skillRoot, 'scripts');
const assets = [
  { name: 'workbuddyLogo', path: 'assets/brand/workbuddy-logo.png', module: 'embedded-workbuddy-logo.mjs' },
  { name: 'zhihuijiLogo', path: 'assets/brand/zhihuiji-logo.png', module: 'embedded-zhihuiji-logo.mjs' },
  { name: 'zhihuijiQr', path: 'assets/brand/zhihuiji-qr.png', module: 'embedded-zhihuiji-qr.mjs' },
  { name: 'calendarHeader', path: 'assets/calendar/header-store-calendar.png', module: 'embedded-calendar-header.mjs' },
  { name: 'monthlyHeader', path: 'assets/monthly-report/header-overview-glass-cutout-v3.png', module: 'embedded-monthly-header.mjs' }
];

const imports = [];
const rows = [];
for (const asset of assets) {
  const buffer = readFileSync(join(skillRoot, asset.path));
  const dataUrl = `data:image/png;base64,${buffer.toString('base64')}`;
  writeFileSync(
    join(scriptRoot, asset.module),
    `// Generated by scripts/build-embedded-assets.mjs. Do not edit.\nexport default ${JSON.stringify(dataUrl)};\n`,
    'utf8'
  );
  imports.push(`import ${asset.name} from './${asset.module}';`);
  rows.push({
    ...asset,
    size: buffer.length,
    sha256: createHash('sha256').update(buffer).digest('hex')
  });
}

const indexSource = `${imports.join('\n')}
import { createHash } from 'node:crypto';

const PREFIX = 'data:image/png;base64,';
const ASSETS = Object.freeze({
${rows.map((row) => `  ${JSON.stringify(row.path)}: ${row.name}`).join(',\n')}
});

export const EMBEDDED_ASSET_META = Object.freeze({
${rows.map((row) => `  ${JSON.stringify(row.path)}: Object.freeze({ size: ${row.size}, sha256: '${row.sha256}' })`).join(',\n')}
});

export function embeddedImageData(path) {
  const value = ASSETS[path];
  if (!value) throw new Error(\`未找到内置图片资源：\${path}\`);
  return value;
}

export function validateEmbeddedAssets() {
  for (const [path, meta] of Object.entries(EMBEDDED_ASSET_META)) {
    const value = embeddedImageData(path);
    if (!value.startsWith(PREFIX)) throw new Error(\`内置图片格式错误：\${path}\`);
    const buffer = Buffer.from(value.slice(PREFIX.length), 'base64');
    const sha256 = createHash('sha256').update(buffer).digest('hex');
    if (buffer.length !== meta.size || sha256 !== meta.sha256) throw new Error(\`内置图片校验失败：\${path}\`);
  }
  return { ok: true, count: Object.keys(EMBEDDED_ASSET_META).length };
}
`;
writeFileSync(join(scriptRoot, 'embedded-assets.mjs'), indexSource, 'utf8');

console.log(JSON.stringify({ ok: true, asset_count: rows.length, files: rows.map((row) => row.module) }, null, 2));
